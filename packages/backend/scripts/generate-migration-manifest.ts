import { readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const journalPath = join(root, "drizzle/meta/_journal.json");
const outputPath = join(root, "src/shared/database/migration-files.ts");
const check = process.argv.includes("--check");

type Journal = {
  entries: { idx: number; tag: string; when: number }[];
};

const journal = JSON.parse(await readFile(journalPath, "utf8")) as Journal;
if (!journal.entries.length)
  throw new Error("The Drizzle migration journal is empty.");

const imports = journal.entries
  .map(
    (entry, index) =>
      `import migration${index} from "../../../drizzle/${entry.tag}.sql" with { type: "text" };`,
  )
  .join("\n");
const entries = journal.entries
  .map(
    (entry, index) => `  {
    tag: "${entry.tag}",
    when: ${entry.when},
    historical: ${entry.tag === "0000_desktop"},
    sql: migration${index},
  },`,
  )
  .join("\n");

const content = `// Generated by scripts/generate-migration-manifest.ts.
// Run \`bun run db:generate\` after adding or changing a Drizzle migration.
import type { DrizzleMigrationFile } from "./migration-runner";
${imports}

export const drizzleMigrations: DrizzleMigrationFile[] = [
${entries}
];
`;

if (check) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== content) {
    console.error(
      "The Drizzle migration manifest is out of date. Run `bun run db:generate` in packages/backend.",
    );
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, content);
}
